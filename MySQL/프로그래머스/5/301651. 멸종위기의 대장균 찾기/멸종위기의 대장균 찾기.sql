WITH RECURSIVE CHILDNODE AS (
    SELECT ID, PARENT_ID, 1 AS GENERATION
    FROM ECOLI_DATA
    WHERE PARENT_ID IS NULL
    
    UNION ALL
    
    SELECT A.ID, A.PARENT_ID, C.GENERATION + 1
    FROM ECOLI_DATA AS A
    JOIN CHILDNODE AS C ON A.PARENT_ID = C.ID
)
SELECT COUNT(*), GENERATION
FROM CHILDNODE
WHERE ID NOT IN (SELECT DISTINCT PARENT_ID FROM ECOLI_DATA WHERE PARENT_ID IS NOT NULL)
GROUP BY GENERATION
ORDER BY GENERATION;