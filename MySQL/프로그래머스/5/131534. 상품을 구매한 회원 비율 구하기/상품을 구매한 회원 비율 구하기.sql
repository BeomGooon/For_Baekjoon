SELECT YEAR(B.SALES_DATE) AS Y, MONTH(B.SALES_DATE) AS MON, COUNT(DISTINCT B.USER_ID) AS PURCHASED_USERS, ROUND(COUNT(DISTINCT B.USER_ID)/C.NUM_USER, 1) AS PURCHASED_RATIO
FROM (SELECT USER_ID FROM USER_INFO WHERE JOINED BETWEEN DATE('2021-01-01') AND DATE('2021-12-31')) AS A
JOIN ONLINE_SALE AS B ON A.USER_ID = B.USER_ID, 
(SELECT COUNT(USER_ID) AS NUM_USER FROM USER_INFO WHERE JOINED BETWEEN DATE('2021-01-01') AND DATE('2021-12-31')) AS C
GROUP BY YEAR(B.SALES_DATE), MONTH(B.SALES_DATE)
ORDER BY YEAR(B.SALES_DATE), MONTH(B.SALES_DATE);