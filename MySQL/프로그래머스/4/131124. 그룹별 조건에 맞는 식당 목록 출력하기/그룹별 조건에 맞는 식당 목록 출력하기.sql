SELECT A.MEMBER_NAME, B.REVIEW_TEXT, DATE_FORMAT(B.REVIEW_DATE, '%Y-%m-%d') AS REVIEW_DATE
FROM (
    SELECT A.MEMBER_ID, A.MEMBER_NAME
    FROM MEMBER_PROFILE AS A
    JOIN (
        SELECT RANK() OVER (ORDER BY INP.NUM DESC) AS RNK, INP.MEMBER_ID
        FROM (
            SELECT COUNT(*) AS NUM, MEMBER_ID
            FROM REST_REVIEW
            GROUP BY MEMBER_ID
        ) AS INP
    ) AS B ON B.RNK = 1 AND A.MEMBER_ID = B.MEMBER_ID
) AS A
JOIN REST_REVIEW AS B ON A.MEMBER_ID = B.MEMBER_ID
ORDER BY REVIEW_DATE ASC, REVIEW_TEXT ASC;