WITH CTE AS (
    SELECT EMP_NO, AVG(SCORE) AS SCORE
    FROM HR_GRADE
    GROUP BY EMP_NO
)

SELECT A.EMP_NO,
    A.EMP_NAME,
    CASE
        WHEN B.SCORE >= 96 THEN 'S'
        WHEN B.SCORE >= 90 THEN 'A'
        WHEN B.SCORE >= 80 THEN 'B'
        ELSE 'C'
    END AS GRADE,
    CASE
        WHEN B.SCORE >= 96 THEN (0.2*A.SAL)
        WHEN B.SCORE >= 90 THEN (0.15*A.SAL)
        WHEN B.SCORE >= 80 THEN (0.1*A.SAL)
        ELSE 0
    END AS BONUS
FROM HR_EMPLOYEES A
JOIN CTE B ON A.EMP_NO = B.EMP_NO
ORDER BY A.EMP_NO ASC;