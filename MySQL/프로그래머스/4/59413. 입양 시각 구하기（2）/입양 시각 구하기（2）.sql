WITH RECURSIVE CHILDNODE AS (
    SELECT 0 AS HOUR, 0 AS COUNT
    
    UNION ALL
    
    SELECT C.HOUR + 1 AS HOUR, 0 AS COUNT
    FROM CHILDNODE C
    WHERE C.HOUR < 23
)
SELECT C.HOUR, IFNULL(INP.COUNT, 0) AS HOUR
FROM CHILDNODE C
LEFT JOIN (
    SELECT HOUR(DATETIME) AS HOUR, COUNT(*) AS COUNT
    FROM ANIMAL_OUTS
    GROUP BY HOUR(DATETIME)
) INP ON C.HOUR = INP.HOUR
;