SELECT D.GRADE, D.ID, D.EMAIL
FROM (
SELECT IF((A.SKILL_CODE & FRONT.CODE > 0) AND (A.SKILL_CODE & PYTHON.CODE > 0), 'A', IF(A.SKILL_CODE & CSHARP.CODE > 0, 'B', IF((A.SKILL_CODE & FRONT.CODE > 0), 'C', 'D'))) AS GRADE, A.ID, A.EMAIL
FROM DEVELOPERS AS A, (SELECT SUM(K.CODE) AS CODE FROM SKILLCODES AS K WHERE K.CATEGORY = 'Front End') AS FRONT, (SELECT K.CODE FROM SKILLCODES AS K WHERE K.NAME = 'C#') AS CSHARP, (SELECT K.CODE FROM SKILLCODES AS K WHERE K.NAME = 'Python') AS PYTHON
    ) AS D
WHERE D.GRADE != 'D'
ORDER BY GRADE ASC, ID ASC;