SELECT C.FLAVOR
FROM (
    SELECT B.FLAVOR, RANK() OVER (ORDER BY B.TOTAL_ORDER DESC) AS RNK
    FROM (
        SELECT A.FLAVOR, SUM(A.TOTAL_ORDER) AS TOTAL_ORDER
        FROM (
            SELECT FLAVOR, TOTAL_ORDER
            FROM FIRST_HALF

            UNION ALL

            SELECT FLAVOR, TOTAL_ORDER
            FROM JULY
        ) AS A
        GROUP BY A.FLAVOR
    ) AS B
) AS C
WHERE C.RNK <= 3
ORDER BY C.RNK ASC;