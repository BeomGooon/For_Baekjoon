SELECT INP.ID,
    CASE 
        WHEN INP.RANK_RATIO <= 0.25 THEN 'CRITICAL'
        WHEN INP.RANK_RATIO <= 0.5 THEN 'HIGH'
        WHEN INP.RANK_RATIO <= 0.75 THEN 'MEDIUM'
        ELSE 'LOW'
    END AS COLONY_NAME
FROM (SELECT A.ID,
    (RANK() OVER (ORDER BY A.SIZE_OF_COLONY DESC))/B.SIZE AS RANK_RATIO
FROM ECOLI_DATA A, (SELECT COUNT(*) AS SIZE FROM ECOLI_DATA) B
) INP
ORDER BY ID;