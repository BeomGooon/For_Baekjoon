WITH RECURSIVE CHILDNODE AS (
    SELECT ID, PARENT_ID, GENOTYPE, 0 AS PARENT_GENOTYPE
    FROM ECOLI_DATA
    WHERE PARENT_ID IS NULL
    
    UNION ALL
    
    SELECT E.ID, E.PARENT_ID, E.GENOTYPE, C.GENOTYPE AS PARENT_GENOTYPE
    FROM ECOLI_DATA AS E
    JOIN CHILDNODE AS C ON E.PARENT_ID = C.ID
)
SELECT ID, GENOTYPE, PARENT_GENOTYPE
FROM CHILDNODE
WHERE GENOTYPE & PARENT_GENOTYPE = PARENT_GENOTYPE AND PARENT_ID IS NOT NULL
ORDER BY ID ASC;